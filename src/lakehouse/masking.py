"""Column-level PII masking, a leak scan for consumer tables, and Unity Catalog SQL generation.

Masking methods (identical in the pandas and Spark engines):

=============  ==========================================  =============================
method         output                                      why
=============  ==========================================  =============================
redact         ``***``                                     value is never needed downstream
hash           ``sha256(salt || lower(trim(value)))``      joinable and countable, not readable
mask_last4     ``**********6789``                          enough for support look-ups
year_only      ``1994``                                    keeps age analysis, drops the exact date
=============  ==========================================  =============================

The salt comes from an environment variable (on Databricks: a secret scope backed by Key Vault).
"""
from __future__ import annotations

import hashlib
import re
from datetime import date

import pandas as pd

from .config import PiiPolicy

EMAIL_RX = re.compile(r"[^@\s]+@[^@\s]+\.[a-z]{2,}", re.I)
PHONE_RX = re.compile(r"(\+?\d[\d\s-]{8,}\d)")
DATE_RX = re.compile(r"^\d{4}-\d{2}-\d{2}$")


def hash_value(value: str | None, salt: str) -> str | None:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return None
    return hashlib.sha256((salt + str(value).strip().lower()).encode()).hexdigest()


def mask_last4(value: str | None) -> str | None:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return None
    v = str(value)
    return "*" * max(len(v) - 4, 0) + v[-4:]


def year_only(value) -> int | None:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return None
    if isinstance(value, date):
        return value.year
    return int(str(value)[:4])


def apply_policy(df: pd.DataFrame, methods: dict[str, str], salt: str) -> pd.DataFrame:
    """Return a copy with every policy column masked. ``year_only`` renames ``x`` to ``x_year``."""
    out = df.copy()
    for col, method in methods.items():
        if col not in out:
            continue
        if method == "redact":
            out[col] = out[col].map(lambda v: None if v is None or v != v else "***")
        elif method == "hash":
            out[col] = out[col].map(lambda v: hash_value(v, salt))
        elif method == "mask_last4":
            out[col] = out[col].map(mask_last4)
        elif method == "year_only":
            out[f"{col}_year"] = out[col].map(year_only).astype("Int64")
            out = out.drop(columns=col)
        else:
            raise ValueError(method)
    return out


def scan_for_leaks(tables: dict[str, pd.DataFrame], raw_values: set[str]) -> list[dict]:
    """Find raw PII in consumer tables: exact matches with known raw values, emails and phone numbers."""
    findings = []
    for name, df in tables.items():
        for col in df.columns:
            if not (pd.api.types.is_object_dtype(df[col]) or pd.api.types.is_string_dtype(df[col])):
                continue
            values = df[col].dropna().astype(str)
            for v in values.unique():
                kind = None
                if v in raw_values:
                    kind = "raw_value"
                elif EMAIL_RX.search(v):
                    kind = "email_pattern"
                elif PHONE_RX.fullmatch(v) and not DATE_RX.match(v):
                    kind = "phone_pattern"
                if kind:
                    findings.append({"table": name, "column": col, "kind": kind})
                    break
    return findings


def raw_pii_values(customers: pd.DataFrame, policy: PiiPolicy) -> set[str]:
    values: set[str] = set()
    for col in policy.for_entity("customers"):
        if col in customers:
            values |= {str(v) for v in customers[col].dropna().unique() if not DATE_RX.match(str(v))}
    return values


# ---------------------------------------------------------------------------------------- Unity Catalog
_UC_BODY = {
    "redact": "'***'",
    "hash": "sha2(concat(secret('{scope}', '{key}'), lower(trim(v))), 256)",
    "mask_last4": "concat(repeat('*', greatest(length(v) - 4, 0)), right(v, 4))",
    "year_only": "make_date(year(v), 1, 1)",
}
_UC_TYPE = {"redact": "STRING", "hash": "STRING", "mask_last4": "STRING", "year_only": "DATE"}


def unity_catalog_sql(policy: PiiPolicy, catalog: str = "main", schema: str = "silver",
                      scope: str = "lakehouse", key: str = "pii-hash-salt") -> str:
    """Column-mask SQL for Databricks Unity Catalog, generated from the same policy file.

    Members of the reader group see raw values; everyone else gets the masked value at query time.
    """
    lines = [
        "-- Generated by `python -m lakehouse uc-sql` from config/pipeline.yaml. Do not edit by hand.",
        f"-- Members of `{policy.reader_group}` see raw values; everyone else sees the masked value.",
        f"USE CATALOG {catalog};",
        f"USE SCHEMA {schema};",
        "",
    ]
    for method in sorted(set(policy.columns.values())):
        body = _UC_BODY[method].format(scope=scope, key=key)
        rtype = _UC_TYPE[method]
        lines += [
            f"CREATE OR REPLACE FUNCTION pii_mask_{method}(v {rtype})",
            f"  RETURNS {rtype}",
            f"  RETURN CASE WHEN is_account_group_member('{policy.reader_group}') THEN v ELSE {body} END;",
            "",
        ]
    for target, method in sorted(policy.columns.items()):
        table, col = target.split(".", 1)
        lines.append(f"ALTER TABLE {table} ALTER COLUMN {col} SET MASK pii_mask_{method};")
    return "\n".join(lines) + "\n"
